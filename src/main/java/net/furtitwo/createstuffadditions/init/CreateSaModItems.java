	// ---- helpers ----

	/** Plain crafting ingredient. */
	private static DeferredItem<Item> simple(String name, int maxStack) {
		return REGISTRY.register(name, () -> new Item(new Item.Properties().stacksTo(maxStack)));
	}

	/** Intermediate item of a Create sequenced-assembly recipe. */
	private static DeferredItem<Item> incomplete(String name, int maxStack) {
		return REGISTRY.register(name, () -> new SequencedAssemblyItem(new Item.Properties().stacksTo(maxStack)));
	}

	private static DeferredItem<Item> tool(String name, Kind kind, CSAToolTier tier, float damage, float attackSpeed) {
		return REGISTRY.register(name, () -> CSATools.create(kind, tier, damage, attackSpeed));
	}

	private static DeferredItem<Item> tool(String name, Kind kind, CSAToolTier tier, float damage, float attackSpeed, double reachBonus, ToolBehaviour behaviour) {
		return REGISTRY.register(name, () -> CSATools.create(kind, tier, damage, attackSpeed, reachBonus, behaviour));
	}

	private static DeferredItem<Item> armor(String name, Supplier<Holder<ArmorMaterial>> material, ArmorItem.Type type, int durability, boolean piglinNeutral) {
		return REGISTRY.register(name, () -> new CSAArmorItem(material, type, durability, piglinNeutral));
	}

	private static DeferredItem<Item> tank(String name, FuelType.Resource resource, FluidTankItem.Size size) {
		return REGISTRY.register(name, () -> new FluidTankItem(resource, size));
	}

	private static DeferredItem<Item> block(DeferredHolder<Block, Block> block) {
		return REGISTRY.register(block.getId().getPath(), () -> new BlockItem(block.get(), new Item.Properties()));
	}
